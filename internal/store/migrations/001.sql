CREATE TABLE IF NOT EXISTS events (
 seq INTEGER PRIMARY KEY, id TEXT NOT NULL UNIQUE, version INTEGER NOT NULL,
 type TEXT NOT NULL, actor TEXT NOT NULL, channel_id TEXT NOT NULL DEFAULT '',
 idempotency_key TEXT UNIQUE, payload BLOB NOT NULL, ts TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS members (id TEXT PRIMARY KEY, handle TEXT NOT NULL UNIQUE, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS channels (id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS messages (id TEXT PRIMARY KEY, channel_id TEXT NOT NULL REFERENCES channels(id), thread_id TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, data BLOB NOT NULL);
CREATE INDEX IF NOT EXISTS messages_channel_time ON messages(channel_id, created_at, id);
CREATE INDEX IF NOT EXISTS messages_thread ON messages(thread_id);
CREATE TABLE IF NOT EXISTS runs (id TEXT PRIMARY KEY, channel_id TEXT NOT NULL, state TEXT NOT NULL, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS approvals (id TEXT PRIMARY KEY, state TEXT NOT NULL, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS lanes (id TEXT PRIMARY KEY, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS unread (channel_id TEXT NOT NULL, member_id TEXT NOT NULL, last_read_seq INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(channel_id, member_id));
